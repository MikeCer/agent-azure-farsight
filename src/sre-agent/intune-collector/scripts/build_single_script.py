from __future__ import annotations

import base64
import json
import shutil
from pathlib import Path


COLLECTOR_ROOT = Path(__file__).resolve().parents[1]
PROJECT_ROOT = COLLECTOR_ROOT.parent
PACKAGE_ROOT = COLLECTOR_ROOT / "src" / "intune_diagnostics"
OUTPUT = COLLECTOR_ROOT / "dist" / "intune_diagnostics_tool.py"
SRE_AGENT_TOOL_OUTPUT = PROJECT_ROOT / "agent" / "tools" / "intune_diagnostics_tool.py"


def main() -> int:
    modules: dict[str, str] = {}
    for path in sorted(PACKAGE_ROOT.glob("*.py")):
        module_name = "intune_diagnostics" if path.name == "__init__.py" else f"intune_diagnostics.{path.stem}"
        modules[module_name] = base64.b64encode(path.read_bytes()).decode("ascii")

    payload = json.dumps(modules, indent=2, sort_keys=True)
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(_render(payload), encoding="utf-8")
    OUTPUT.chmod(0o755)
    print(f"Wrote {OUTPUT}")

    SRE_AGENT_TOOL_OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(OUTPUT, SRE_AGENT_TOOL_OUTPUT)
    SRE_AGENT_TOOL_OUTPUT.chmod(0o755)
    print(f"Wrote {SRE_AGENT_TOOL_OUTPUT}")
    return 0


